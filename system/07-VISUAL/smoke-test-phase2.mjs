#!/usr/bin/env bun
// 07-VISUAL/smoke-test-phase2.mjs — OrangeEye Phase-2 smoke test.
//
// Phase-1 (./smoke-test.mjs) proved the synchronous /ingest -> /query ->
// /describe path. Phase-2 adds the four pieces this script exercises end-to-end:
//
//   (a) PDF batch ingest via /v1/visual/ingest/batch — multiple files at once
//       must enqueue without OOM'ing the python worker;
//   (b) /v1/visual/queue — list + per-id lookup work and report status
//       transitions queued -> running -> done (or error, honestly);
//   (c) OpenVINO IR present at $COLPALI_OPENVINO_DIR — checked via the
//       ColPali /health backend tag (no IR -> warn, do not fail; this is a
//       *capability* probe, not a hard gate);
//   (d) Temporal video ingest via /v1/visual/video/ingest — a small synthetic
//       MP4 is generated by ffmpeg, posted, and the per-frame queue ids land.
//
// Exit codes:
//   0 — all required steps green (capability probes may WARN without failing)
//   1 — a required assertion failed (specific step printed in red)
//   2 — pre-flight fatal (gateway or colpali-service unreachable)
//   3 — internal harness bug (fixture build failed, ffmpeg missing on PATH for
//       the video step — we still warn-degrade rather than crash if possible)
//
// Required dependencies (all loopback):
//   - OrangeLLM gateway on 127.0.0.1:1337
//   - colpali-service on 127.0.0.1:7440 with /enqueue, /queue, /queue/:id mounted
//   - Qdrant on 127.0.0.1:6333 (so the queue runner can land patches)
//   - ffmpeg on PATH (skipped with WARN if absent)
//
// Frontier-Isolation: every URL here is loopback. No external DNS lookups,
// no API keys, no outbound calls.
//
// What this does NOT do:
//   - no retries / backoff (binary green/red)
//   - no perf assertions
//   - no cleanup of Qdrant points (idempotent at the doc_id level)
//   - no cleanup of the temp frames dir (the queue runner owns those files;
//     operator cleanup cron sweeps stale orangeeye-frames-* dirs)

import { buildSmokePdf, SMOKE_TEXT_LINES } from "./test-pdf-generator.mjs";
import { writeFileSync, mkdtempSync, existsSync, rmSync } from "node:fs";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";

const GATEWAY      = process.env.ORANGELLM_GATEWAY   || "http://127.0.0.1:1337";
const COLPALI_BASE = process.env.COLPALI_BASE        || "http://127.0.0.1:7440";

// Poll budgets — the queue runner is single-flight and processes one row at a
// time, so 3 PDFs at ~5s each + a handful of frames at ~3s each is the bound
// we plan for. Leave a healthy margin so a slow first-load (transformers cold
// import) doesn't flake the suite.
const QUEUE_POLL_INTERVAL_MS = Number(process.env.PHASE2_POLL_MS    || 1_000);
const QUEUE_TIMEOUT_MS       = Number(process.env.PHASE2_TIMEOUT_MS || 180_000);
const FETCH_TIMEOUT_MS       = Number(process.env.PHASE2_FETCH_MS   || 30_000);

const FFMPEG = process.env.PHASE2_FFMPEG || "ffmpeg";

// -------------------- ANSI helpers --------------------

const NO_COLOR = process.env.NO_COLOR != null || !process.stdout.isTTY;
const c = {
  green: (s) => (NO_COLOR ? s : `\x1b[32m${s}\x1b[0m`),
  red:   (s) => (NO_COLOR ? s : `\x1b[31m${s}\x1b[0m`),
  yel:   (s) => (NO_COLOR ? s : `\x1b[33m${s}\x1b[0m`),
  dim:   (s) => (NO_COLOR ? s : `\x1b[2m${s}\x1b[0m`),
  bold:  (s) => (NO_COLOR ? s : `\x1b[1m${s}\x1b[0m`),
};

// -------------------- fetch helper --------------------

async function timedFetch(url, init = {}) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), FETCH_TIMEOUT_MS);
  const start = performance.now();
  try {
    const res = await fetch(url, { ...init, signal: ctrl.signal });
    const ms = Math.round(performance.now() - start);
    let body = null;
    const text = await res.text();
    if (text) {
      try { body = JSON.parse(text); }
      catch { body = { _raw: text.slice(0, 500) }; }
    }
    return { ok: res.ok, status: res.status, body, ms };
  } catch (err) {
    const ms = Math.round(performance.now() - start);
    return { ok: false, status: 0, err: String(err?.message || err), ms };
  } finally {
    clearTimeout(timer);
  }
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

// -------------------- step results --------------------

const results = [];
let warnings = 0;

function record(step, ok, summary, detail = null, level = "fail") {
  const status = ok ? "PASS" : (level === "warn" ? "WARN" : "FAIL");
  results.push({ step, ok, summary, detail, status });
  if (!ok && level === "warn") warnings++;
  const tag = ok ? c.green("PASS") : (level === "warn" ? c.yel("WARN") : c.red("FAIL"));
  console.log(`[${tag}] ${step}: ${summary}`);
  if (!ok && detail) {
    const lines = String(detail).split("\n").slice(0, 8);
    for (const line of lines) console.log(c.dim(`        ${line}`));
  }
}

// -------------------- step 1: preflight --------------------

async function step1_preflight() {
  const probes = [];

  // Gateway reachability — POST /v1/visual/queue (GET) is the cheapest health
  // check that exercises the Phase-2 boundary additions.
  {
    const r = await timedFetch(`${GATEWAY}/v1/visual/queue?limit=1`);
    probes.push({
      name: "gateway /v1/visual/queue",
      ok: r.ok || r.status === 503, // 503 means colpali down but gateway alive
      detail: r.ok ? `${r.ms}ms` : (r.err || `HTTP ${r.status}: ${JSON.stringify(r.body).slice(0, 120)}`),
    });
  }

  // colpali-service /queue directly — we want both the gateway path AND the
  // backend path to be green so failure attribution is unambiguous.
  {
    const r = await timedFetch(`${COLPALI_BASE}/queue?limit=1`);
    probes.push({
      name: "colpali :7440 /queue",
      ok: r.ok,
      detail: r.ok ? `${r.ms}ms counts=${JSON.stringify(r.body?.counts || {})}` : (r.err || `HTTP ${r.status}`),
    });
  }

  const allGreen = probes.every((p) => p.ok);
  const summary = probes
    .map((p) => `${p.ok ? c.green("ok") : c.red("down")} ${p.name}`)
    .join(" · ");
  record(
    "step-1 preflight",
    allGreen,
    summary,
    probes.filter((p) => !p.ok).map((p) => `${p.name}: ${p.detail}`).join("\n"),
  );
  return allGreen;
}

// -------------------- step 2: OpenVINO capability probe --------------------
//
// We hit colpali /health (if exposed) and look for a `backend.kind === "openvino"`
// field. If absent or `transformers`, we WARN — Phase-2 is supposed to ship the
// OV path but it's a perf gate, not a correctness gate.

async function step2_openvino_probe() {
  const r = await timedFetch(`${COLPALI_BASE}/health`);
  if (!r.ok) {
    record(
      "step-2 openvino-probe",
      false,
      `colpali /health unreachable (${r.err || `HTTP ${r.status}`}) — backend tag unknown`,
      null,
      "warn",
    );
    return true;
  }
  const backend = r.body?.backend ?? r.body?.backend_kind ?? null;
  const kind = typeof backend === "string" ? backend : backend?.kind;
  if (kind === "openvino") {
    record("step-2 openvino-probe", true, `backend=openvino (device=${backend?.device || "?"})`);
    return true;
  }
  record(
    "step-2 openvino-probe",
    false,
    `backend=${kind || "(unknown)"} — falling back to transformers; perf-degraded but functional`,
    backend?.reason || JSON.stringify(r.body).slice(0, 200),
    "warn",
  );
  return true;
}

// -------------------- step 3: PDF batch ingest --------------------

let BATCH_IDS = [];
let TMP_PDFS = [];

async function step3_batch_pdf() {
  // Generate three small PDFs in a temp dir. We mutate the smoke text per file
  // so each PDF has a distinct SHA and the queue rows are individually traceable.
  const tmp = mkdtempSync(join(tmpdir(), "orangeeye-phase2-pdfs-"));
  const paths = [];
  try {
    for (let i = 0; i < 3; i++) {
      const lines = [
        `OrangeEye Phase-2 batch fixture ${i + 1} of 3`,
        `Variant token: phase2-${i + 1}-${Date.now()}`,
        ...SMOKE_TEXT_LINES.slice(0, 4),
      ];
      const bytes = buildSmokePdf(lines);
      const p = join(tmp, `phase2-batch-${i + 1}.pdf`);
      writeFileSync(p, bytes);
      paths.push(p);
    }
  } catch (err) {
    record("step-3 batch-pdf", false, "fixture build failed", err.message);
    process.exit(3);
  }
  TMP_PDFS = paths;

  // POST /v1/visual/ingest/batch
  const post = await timedFetch(`${GATEWAY}/v1/visual/ingest/batch`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      paths,
      lane: "doc",
      source_hint: "phase2 batch smoke",
    }),
  });
  if (post.status !== 202) {
    record("step-3 batch-pdf",
      false,
      `expected 202, got HTTP ${post.status}`,
      JSON.stringify(post.body).slice(0, 400));
    return false;
  }
  const ids = post.body?.ids;
  if (!Array.isArray(ids) || ids.length !== paths.length) {
    record("step-3 batch-pdf",
      false,
      `expected ${paths.length} ids, got ${ids?.length}`,
      JSON.stringify(post.body).slice(0, 400));
    return false;
  }
  BATCH_IDS = ids;
  record(
    "step-3 batch-pdf",
    true,
    `enqueued ${ids.length} pdfs (ids=${ids.join(",")}) in ${post.ms}ms`,
  );
  return true;
}

// -------------------- step 4: queue list + drain --------------------

function classify(rows) {
  // Roll up row statuses into counts keyed by status. The /queue endpoint also
  // returns a `counts` summary but we recompute locally so a stale gateway
  // cache doesn't fool us.
  const out = { queued: 0, running: 0, done: 0, error: 0, cancelled: 0 };
  for (const r of rows) {
    if (out[r.status] != null) out[r.status]++;
  }
  return out;
}

async function step4_queue_drain() {
  if (BATCH_IDS.length === 0) {
    record("step-4 queue-drain", false, "no batch ids from step-3 — skipping");
    return false;
  }

  // 4a. /queue list must surface at least our 3 ids with a status we recognise.
  const list = await timedFetch(`${GATEWAY}/v1/visual/queue?limit=200`);
  if (!list.ok) {
    record(
      "step-4 queue-drain",
      false,
      `/v1/visual/queue list failed: HTTP ${list.status}`,
      JSON.stringify(list.body).slice(0, 300),
    );
    return false;
  }
  const seenIds = new Set((list.body?.rows || []).map((r) => r.id));
  const missing = BATCH_IDS.filter((id) => !seenIds.has(id));
  if (missing.length) {
    record(
      "step-4 queue-drain",
      false,
      `queue list missing ids: ${missing.join(",")}`,
      `seen=${[...seenIds].slice(0, 20).join(",")}`,
    );
    return false;
  }

  // 4b. Poll /queue/:id for each id until each leaves {queued,running}.
  const deadline = Date.now() + QUEUE_TIMEOUT_MS;
  const finalStatuses = new Map();
  for (const id of BATCH_IDS) {
    let terminal = null;
    while (Date.now() < deadline) {
      const r = await timedFetch(`${GATEWAY}/v1/visual/queue/${id}`);
      if (!r.ok) {
        record(
          "step-4 queue-drain",
          false,
          `/v1/visual/queue/${id} failed: HTTP ${r.status}`,
          JSON.stringify(r.body).slice(0, 300),
        );
        return false;
      }
      const status = r.body?.status;
      if (status === "done" || status === "error" || status === "cancelled") {
        terminal = { status, body: r.body };
        break;
      }
      await sleep(QUEUE_POLL_INTERVAL_MS);
    }
    if (!terminal) {
      record(
        "step-4 queue-drain",
        false,
        `id=${id} did not reach a terminal state within ${QUEUE_TIMEOUT_MS}ms`,
      );
      return false;
    }
    finalStatuses.set(id, terminal.status);
  }

  // 4c. Summarise. At least one of the three must hit `done`. Errors are
  //     tolerated (e.g. the python worker may fail on a degenerate fixture)
  //     but we surface them honestly rather than swallow.
  const summary = classify([...finalStatuses.entries()].map(([id, status]) => ({ id, status })));
  const anyDone = summary.done > 0;
  const detail = `done=${summary.done} error=${summary.error} cancelled=${summary.cancelled}`;
  if (!anyDone) {
    record(
      "step-4 queue-drain",
      false,
      `no batch row reached status=done (${detail})`,
      [...finalStatuses.entries()].map(([id, s]) => `id=${id} status=${s}`).join("\n"),
    );
    return false;
  }
  record("step-4 queue-drain", true, `drain ok — ${detail}`);
  return true;
}

// -------------------- step 5: video ingest --------------------

function ffmpegAvailable() {
  try {
    const r = spawnSync(FFMPEG, ["-version"], { stdio: "ignore", windowsHide: true });
    return r.status === 0;
  } catch {
    return false;
  }
}

async function step5_video_ingest() {
  if (!ffmpegAvailable()) {
    record(
      "step-5 video-ingest",
      false,
      `ffmpeg not on PATH (${FFMPEG}) — video ingest path not exercised`,
      null,
      "warn",
    );
    return true;
  }

  // Generate a 4-second synthetic MP4 with the lavfi testsrc pattern. No
  // external assets, deterministic dimensions, and the timecode overlay gives
  // ColQwen2.5 something visually distinct per frame.
  const tmp = mkdtempSync(join(tmpdir(), "orangeeye-phase2-video-"));
  const videoPath = join(tmp, "smoke.mp4");
  const gen = spawnSync(
    FFMPEG,
    [
      "-y",
      "-f", "lavfi",
      "-i", "testsrc=duration=4:size=320x240:rate=10",
      "-pix_fmt", "yuv420p",
      "-loglevel", "error",
      videoPath,
    ],
    { stdio: ["ignore", "pipe", "pipe"], windowsHide: true, timeout: 60_000 },
  );
  if (gen.status !== 0 || !existsSync(videoPath)) {
    record(
      "step-5 video-ingest",
      false,
      `ffmpeg fixture-gen failed (exit=${gen.status})`,
      String(gen.stderr || "").slice(0, 400),
      "warn",
    );
    return true;
  }

  // POST /v1/visual/video/ingest — interval_sec=1 against a 4s clip should
  // produce ~4 frames. We assert >=2 to keep the suite resilient to ffmpeg's
  // -vsync vfr duplicate-drop on the testsrc pattern.
  const post = await timedFetch(`${GATEWAY}/v1/visual/video/ingest`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      path: videoPath,
      interval_sec: 1,
      max_frames: 10,
      lane: "video-frame",
      source_hint: "phase2 video smoke",
    }),
  });
  if (post.status !== 202) {
    record(
      "step-5 video-ingest",
      false,
      `expected 202, got HTTP ${post.status}`,
      JSON.stringify(post.body).slice(0, 400),
    );
    return false;
  }
  const frames = post.body?.frames_extracted ?? 0;
  const ids = post.body?.ids ?? [];
  if (frames < 2 || ids.length !== frames) {
    record(
      "step-5 video-ingest",
      false,
      `expected >=2 frames matching ids; got frames=${frames} ids=${ids.length}`,
      JSON.stringify(post.body).slice(0, 400),
    );
    return false;
  }
  record(
    "step-5 video-ingest",
    true,
    `extracted ${frames} frames, enqueued ${ids.length} rows in ${post.ms}ms ` +
    `(frames_dir=${post.body?.frames_dir})`,
  );

  // Cleanup our local mp4 dir. The frames dir is owned by the queue runner,
  // we do NOT touch it here.
  try { rmSync(tmp, { recursive: true, force: true }); }
  catch { /* tolerate */ }

  return true;
}

// -------------------- runner --------------------

async function main() {
  console.log(c.bold("\nOrangeEye Phase-2 smoke test"));
  console.log(c.dim(`  gateway=${GATEWAY}`));
  console.log(c.dim(`  colpali=${COLPALI_BASE}`));
  console.log("");

  const pre = await step1_preflight();
  if (!pre) {
    console.log(c.red("\nPre-flight failed — Phase-2 dependencies unreachable. See README."));
    process.exit(2);
  }

  await step2_openvino_probe();

  const step3 = await step3_batch_pdf();
  if (!step3) {
    finalize();
    process.exit(1);
  }

  const step4 = await step4_queue_drain();
  if (!step4) {
    finalize();
    process.exit(1);
  }

  const step5 = await step5_video_ingest();
  if (!step5) {
    finalize();
    process.exit(1);
  }

  finalize();
  // Cleanup local PDF fixtures (the queue runner already consumed them).
  for (const p of TMP_PDFS) {
    try { rmSync(p, { force: true }); } catch { /* tolerate */ }
  }
  process.exit(0);
}

function finalize() {
  const passed = results.filter((r) => r.ok).length;
  const failed = results.filter((r) => !r.ok && r.status === "FAIL").length;
  const warned = results.filter((r) => !r.ok && r.status === "WARN").length;
  console.log("");
  console.log(c.bold(`Summary: ${passed} pass · ${failed} fail · ${warned} warn`));
  if (warned > 0) {
    console.log(c.yel("  (warnings are capability probes, not correctness failures)"));
  }
}

main().catch((err) => {
  console.error(c.red(`\nsmoke harness crashed: ${err?.stack || err}`));
  process.exit(3);
});
