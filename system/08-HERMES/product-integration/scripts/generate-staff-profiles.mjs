#!/usr/bin/env bun

import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  renameSync,
  rmdirSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const PACK_ROOT = resolve(import.meta.dir, "..");
const CONFIG_ROOT = join(PACK_ROOT, "config");
const ROSTER_PATH = join(CONFIG_ROOT, "staff-roster.json");
const ARCHETYPE_ROOT = join(CONFIG_ROOT, "archetypes");
const EXECUTION_PROFILE_ROOT = join(CONFIG_ROOT, "profiles");
const STAFF_ROOT = join(CONFIG_ROOT, "staff");
const ROLE_INDEX_PATH = join(STAFF_ROOT, "index.json");
const GENERATOR_ID = "scripts/generate-staff-profiles.mjs";
const PRODUCT_NAME = "AE Staff";
const PRODUCT_PHASE = "Wave 4: A 50-Person Company on Your Desktop";
const PRODUCT_ENGINE = "Hermes";
const ROLE_MARKER = `<!-- Generated by ${GENERATOR_ID}. Do not edit. -->`;
const OUTPUT_NAMES = ["ROLE.md", "role.json"];
const ALLOWED_ARCHETYPES = [
  "builder",
  "human-operator",
  "misfit",
  "navigator",
  "researcher",
  "reviewer",
  "visual",
];
const ORANGE_MCP_TOOLS = new Set([
  "orange5_delegate",
  "orange5_health",
  "orange5_order",
  "orange5_receipts",
  "orange5_route",
]);
const HIERARCHY_FIELDS = new Set([
  "children",
  "directReports",
  "hierarchy",
  "manager",
  "parent",
  "parentId",
  "parentRole",
  "roles",
  "subroles",
]);

function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

function isRecord(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function readJson(path, label) {
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    throw new Error(`${label} is not valid JSON: ${error.message}`);
  }
  invariant(isRecord(parsed), `${label} must be a JSON object`);
  return parsed;
}

function text(value, label, { singleLine = false } = {}) {
  invariant(typeof value === "string", `${label} must be a string`);
  const normalized = value.replace(/\r\n?/g, "\n").trim();
  invariant(normalized.length > 0, `${label} must not be empty`);
  invariant(!normalized.includes("\0"), `${label} must not contain NUL bytes`);
  if (singleLine) invariant(!normalized.includes("\n"), `${label} must be one line`);
  return normalized;
}

function stringList(value, label, { min = 0 } = {}) {
  invariant(Array.isArray(value), `${label} must be an array`);
  invariant(value.length >= min, `${label} must contain at least ${min} item(s)`);
  const normalized = value.map((item, index) => text(item, `${label}[${index}]`, { singleLine: true }));
  invariant(new Set(normalized).size === normalized.length, `${label} must not contain duplicates`);
  return normalized;
}

function sameArray(left, right) {
  return Array.isArray(left)
    && Array.isArray(right)
    && left.length === right.length
    && left.every((value, index) => value === right[index]);
}

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function portablePath(path) {
  return relative(PACK_ROOT, path).replaceAll("\\", "/");
}

function assertContained(path, root, label) {
  const full = resolve(path);
  const base = resolve(root);
  invariant(full === base || full.startsWith(`${base}\\`) || full.startsWith(`${base}/`), `${label} escapes ${base}`);
  return full;
}

function assertNoSymlinkPath(path) {
  let cursor = resolve(path);
  const stop = resolve(CONFIG_ROOT);
  assertContained(cursor, stop, "managed output path");
  while (cursor !== stop) {
    if (existsSync(cursor)) {
      invariant(!lstatSync(cursor).isSymbolicLink(), `managed output path contains a symbolic link: ${cursor}`);
    }
    cursor = dirname(cursor);
  }
}

function validateArchetype(raw, fileName) {
  const label = `archetype ${fileName}`;
  invariant(raw.schema === "orange5.hermes-staff-archetype.v1", `${label} has an unsupported schema`);
  const id = text(raw.id, `${label}.id`, { singleLine: true });
  invariant(fileName === `${id}.json`, `${label} filename must match id ${id}`);
  invariant(ALLOWED_ARCHETYPES.includes(id), `${label} is not one of the seven allowed archetypes`);
  const executionProfile = text(raw.executionProfile, `${label}.executionProfile`, { singleLine: true });
  invariant(executionProfile === id, `${label} must map one-to-one to execution profile ${id}`);
  const description = text(raw.description, `${label}.description`);
  const permissionClass = text(raw.permissionClass, `${label}.permissionClass`, { singleLine: true });
  const toolsets = stringList(raw.toolsets, `${label}.toolsets`, { min: 1 });
  const orangeMcpTools = stringList(raw.orangeMcpTools, `${label}.orangeMcpTools`, { min: 1 });
  invariant(toolsets.includes("mcp-orange5"), `${label} must use the filtered Orange MCP toolset`);
  for (const tool of orangeMcpTools) {
    invariant(ORANGE_MCP_TOOLS.has(tool), `${label} exposes unknown Orange MCP tool ${tool}`);
  }
  invariant(typeof raw.workingLeadAllowed === "boolean", `${label}.workingLeadAllowed must be boolean`);
  const soul = text(raw.soul, `${label}.soul`);
  return {
    schema: raw.schema,
    id,
    executionProfile,
    description,
    permissionClass,
    toolsets,
    orangeMcpTools,
    workingLeadAllowed: raw.workingLeadAllowed,
    soul,
  };
}

function validateExecutionProfile(archetype) {
  const profileRoot = join(EXECUTION_PROFILE_ROOT, archetype.executionProfile);
  const configPath = join(profileRoot, "config.yaml");
  invariant(existsSync(configPath), `execution profile ${archetype.executionProfile} is missing config.yaml`);
  let config;
  try {
    config = Bun.YAML.parse(readFileSync(configPath, "utf8"));
  } catch (error) {
    throw new Error(`execution profile ${archetype.executionProfile} has invalid YAML: ${error.message}`);
  }

  invariant(config?.model?.default === "__HERMES_AGENT_MODEL__", `${archetype.id} must preserve __HERMES_AGENT_MODEL__`);
  invariant(config?.model?.base_url === "__ORANGE_MODEL_URL__", `${archetype.id} must preserve __ORANGE_MODEL_URL__`);
  invariant(config?.providers?.orange5?.api === "__ORANGE_MODEL_URL__", `${archetype.id} provider must preserve __ORANGE_MODEL_URL__`);
  invariant(config?.mcp_servers?.orange5?.url === "__ORANGE_MCP_URL__", `${archetype.id} must preserve __ORANGE_MCP_URL__`);
  invariant(
    sameArray(config?.platform_toolsets?.cli, archetype.toolsets),
    `${archetype.id} CLI toolsets do not match its least-privilege archetype`,
  );
  invariant(
    sameArray(config?.platform_toolsets?.api_server, archetype.toolsets),
    `${archetype.id} API toolsets do not match its least-privilege archetype`,
  );
  invariant(
    sameArray(config?.mcp_servers?.orange5?.tools?.include, archetype.orangeMcpTools),
    `${archetype.id} Orange MCP tools do not match its least-privilege archetype`,
  );
}

function loadArchetypes() {
  invariant(existsSync(ARCHETYPE_ROOT), `archetype directory is missing: ${ARCHETYPE_ROOT}`);
  const files = readdirSync(ARCHETYPE_ROOT, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
    .map((entry) => entry.name)
    .sort(compareText);
  invariant(files.length === 7, `archetype directory must contain exactly seven JSON definitions; got ${files.length}`);
  invariant(
    sameArray(files, ALLOWED_ARCHETYPES.map((id) => `${id}.json`)),
    `archetype files must be exactly: ${ALLOWED_ARCHETYPES.join(", ")}`,
  );

  const archetypes = new Map();
  for (const file of files) {
    const archetype = validateArchetype(readJson(join(ARCHETYPE_ROOT, file), `archetype ${file}`), file);
    validateExecutionProfile(archetype);
    archetypes.set(archetype.id, archetype);
  }
  return archetypes;
}

function validateFlatRole(raw, index, archetypes) {
  const label = `staff-roster.roles[${index}]`;
  invariant(isRecord(raw), `${label} must be a flat object`);
  for (const [key, value] of Object.entries(raw)) {
    invariant(!HIERARCHY_FIELDS.has(key), `${label} contains hierarchical field ${key}; staff roles must remain flat`);
    invariant(value !== null, `${label}.${key} must not be null`);
    invariant(!isRecord(value), `${label}.${key} must not contain a nested object`);
    if (Array.isArray(value)) {
      invariant(value.every((item) => typeof item === "string"), `${label}.${key} arrays may contain only strings`);
    } else {
      invariant(["string", "number", "boolean"].includes(typeof value), `${label}.${key} must be a scalar or string array`);
    }
  }

  const id = text(raw.id, `${label}.id`, { singleLine: true });
  invariant(/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id), `${label}.id must be a lowercase filesystem-safe slug`);
  const archetype = text(raw.archetype, `${label}.archetype`, { singleLine: true });
  invariant(archetypes.has(archetype), `${label}.archetype must be one of the seven allowed archetypes`);
  invariant(typeof raw.canLead === "boolean", `${label}.canLead must be boolean`);
  invariant(
    !raw.canLead || archetypes.get(archetype).workingLeadAllowed,
    `${label} cannot be a working lead under archetype ${archetype}`,
  );

  return {
    id,
    title: text(raw.title, `${label}.title`, { singleLine: true }),
    studio: text(raw.studio, `${label}.studio`, { singleLine: true }),
    archetype,
    purpose: text(raw.purpose, `${label}.purpose`),
    concreteOutputs: stringList(raw.concreteOutputs, `${label}.concreteOutputs`, { min: 1 }),
    entryConditions: stringList(raw.entryConditions, `${label}.entryConditions`, { min: 1 }),
    completionContract: stringList(raw.completionContract, `${label}.completionContract`, { min: 1 }),
    forbiddenActions: stringList(raw.forbiddenActions, `${label}.forbiddenActions`, { min: 1 }),
    preferredHandoffs: stringList(raw.preferredHandoffs, `${label}.preferredHandoffs`),
    canLead: raw.canLead,
    modelTier: text(raw.modelTier, `${label}.modelTier`, { singleLine: true }),
    reportsTo: text(raw.reportsTo, `${label}.reportsTo`, { singleLine: true }),
  };
}

function loadRoster(archetypes) {
  invariant(existsSync(ROSTER_PATH), `staff roster is missing: ${ROSTER_PATH}`);
  const raw = readJson(ROSTER_PATH, "staff roster");
  invariant(raw.schema === "orange5.hermes.staff-roster.v1", "staff roster has an unsupported schema");
  invariant(isRecord(raw.organization), "staff roster organization must be an object");
  invariant(raw.organization.name === PRODUCT_NAME, `staff roster organization.name must be ${PRODUCT_NAME}`);
  invariant(raw.organization.productName === PRODUCT_NAME, `staff roster organization.productName must be ${PRODUCT_NAME}`);
  invariant(raw.organization.workTitle === PRODUCT_PHASE, `staff roster organization.workTitle must be ${PRODUCT_PHASE}`);
  invariant(raw.organization.subtitle === `Powered by ${PRODUCT_ENGINE}`, `staff roster subtitle must be Powered by ${PRODUCT_ENGINE}`);
  invariant(raw.organization.structure === "flat", "staff roster organization.structure must be flat");
  invariant(raw.organization.roleCount === 50, "staff roster organization.roleCount must be 50");
  invariant(raw.organization.logicalActionRoleCount === 50, "staff roster logicalActionRoleCount must be 50");
  invariant(raw.organization.executionProfileCount === 7, "staff roster executionProfileCount must be 7");
  invariant(Array.isArray(raw.organization.executionProfiles), "staff roster executionProfiles must be an array");
  invariant(
    sameArray([...raw.organization.executionProfiles].sort(compareText), ALLOWED_ARCHETYPES),
    "staff roster executionProfiles must name exactly the seven hardened Hermes profiles",
  );
  const navigatorId = text(raw.organization.navigatorId, "staff roster organization.navigatorId", { singleLine: true });
  invariant(Array.isArray(raw.roles), "staff roster roles must be an array");
  invariant(raw.roles.length === 50, `staff roster must contain exactly 50 roles; got ${raw.roles.length}`);
  const roles = raw.roles.map((role, index) => validateFlatRole(role, index, archetypes));

  const foldedIds = roles.map((role) => role.id.toLowerCase());
  invariant(new Set(foldedIds).size === 50, "staff roster role ids must be unique, including case-insensitively");
  const roleIds = new Set(roles.map((role) => role.id));
  for (const role of roles) {
    for (const handoff of role.preferredHandoffs) {
      invariant(roleIds.has(handoff), `staff role ${role.id} has unknown preferred handoff ${handoff}`);
    }
  }

  const navigators = roles.filter((role) => role.archetype === "navigator");
  invariant(navigators.length === 1, `staff roster must contain exactly one Navigator; got ${navigators.length}`);
  invariant(navigators[0].id === navigatorId, `the sole Navigator role id must be ${navigatorId}`);
  invariant(navigators[0].canLead, "Navigator must be marked canLead=true");
  invariant(navigators[0].reportsTo === "operator", "Navigator must report directly to the operator");
  for (const role of roles) {
    if (role.id !== navigatorId) {
      invariant(role.reportsTo === navigatorId, `staff role ${role.id} must report directly to ${navigatorId}`);
    }
  }
  invariant(
    sameArray([...new Set(roles.map((role) => role.archetype))].sort(compareText), ALLOWED_ARCHETYPES),
    "staff roster must exercise all seven allowed archetypes",
  );
  return roles.sort((left, right) => compareText(left.id, right.id));
}

function orchestrationFor(role) {
  if (role.archetype === "navigator") {
    return {
      mode: "nested-orchestrator",
      max_concurrent_children: 6,
      max_spawn_depth: 2,
      orchestrator_enabled: true,
    };
  }
  if (role.canLead) {
    return {
      mode: "flat-working-lead",
      max_concurrent_children: 6,
      max_spawn_depth: 1,
      orchestrator_enabled: false,
    };
  }
  return {
    mode: "none",
    max_concurrent_children: 0,
    max_spawn_depth: 0,
    orchestrator_enabled: false,
  };
}

function roleRecord(role, archetype) {
  return {
    schema: "orange5.hermes-logical-role.v1",
    generatedBy: GENERATOR_ID,
    product: PRODUCT_NAME,
    phase: PRODUCT_PHASE,
    engine: PRODUCT_ENGINE,
    id: role.id,
    title: role.title,
    studio: role.studio,
    archetype: role.archetype,
    executionProfile: archetype.executionProfile,
    purpose: role.purpose,
    concreteOutputs: role.concreteOutputs,
    entryConditions: role.entryConditions,
    completionContract: role.completionContract,
    forbiddenActions: role.forbiddenActions,
    preferredHandoffs: role.preferredHandoffs,
    canLead: role.canLead,
    modelTier: role.modelTier,
    reportsTo: role.reportsTo,
    orchestration: orchestrationFor(role),
    effectiveCapabilities: {
      permissionClass: archetype.permissionClass,
      toolsets: archetype.toolsets,
      orangeMcpTools: archetype.orangeMcpTools,
    },
  };
}

function markdownList(values) {
  return values.length ? values.map((value) => `- ${value}`).join("\n") : "- None.";
}

function roleMarkdown(role, archetype) {
  const orchestration = orchestrationFor(role);
  const orchestrationLaw = orchestration.mode === "nested-orchestrator"
    ? "Navigator alone may create a depth-two tree. Keep shared writes and irreversible Orange actions serialized."
    : orchestration.mode === "flat-working-lead"
      ? "You may coordinate one flat layer of direct leaves. You may not create an orchestrator child or a second-level delegation tree."
      : "You may not delegate or orchestrate. Return your bounded result to a preferred handoff.";
  return `${ROLE_MARKER}
# ${role.title}

**Product:** ${PRODUCT_NAME}  
**Phase:** ${PRODUCT_PHASE}  
**Engine:** ${PRODUCT_ENGINE}
**Direct owner:** ${role.reportsTo}

You are the \`${role.id}\` logical action role in ${role.studio}. You run through the hardened \`${archetype.executionProfile}\` Hermes execution profile; you are not a separate Hermes route, gateway, model instance, or manager.

## Purpose

${role.purpose}

## Entry Conditions

${markdownList(role.entryConditions)}

## Concrete Outputs

${markdownList(role.concreteOutputs)}

## Completion Contract

${markdownList(role.completionContract)}

## Forbidden Actions

${markdownList(role.forbiddenActions)}

## Preferred Handoffs

${markdownList(role.preferredHandoffs)}

## Archetype Law

${archetype.soul}

## Runtime Boundary

- Execution profile: \`${archetype.executionProfile}\`
- Permission class: \`${archetype.permissionClass}\`
- Hermes toolsets: ${archetype.toolsets.map((tool) => `\`${tool}\``).join(", ")}
- Orange MCP tools: ${archetype.orangeMcpTools.map((tool) => `\`${tool}\``).join(", ")}
- Model tier: \`${role.modelTier}\`

## Orchestration

${orchestrationLaw}

Working-lead capability is temporary task coordination. It creates no reporting line or permanent hierarchy.
`;
}

function compiledIndex(roles, archetypes) {
  return {
    schema: "orange5.hermes-compiled-role-index.v1",
    generatedBy: GENERATOR_ID,
    product: PRODUCT_NAME,
    phase: PRODUCT_PHASE,
    engine: PRODUCT_ENGINE,
    source: "config/staff-roster.json",
    roleCount: roles.length,
    archetypeCount: archetypes.size,
    executionProfileCount: archetypes.size,
    executionProfiles: [...archetypes.values()].map((archetype) => ({
      archetype: archetype.id,
      executionProfile: archetype.executionProfile,
      permissionClass: archetype.permissionClass,
      toolsets: archetype.toolsets,
      orangeMcpTools: archetype.orangeMcpTools,
    })),
    roles: roles.map((role) => {
      const archetype = archetypes.get(role.archetype);
      return {
        id: role.id,
        title: role.title,
        studio: role.studio,
        archetype: role.archetype,
        executionProfile: archetype.executionProfile,
        canLead: role.canLead,
        modelTier: role.modelTier,
        reportsTo: role.reportsTo,
        orchestration: orchestrationFor(role),
        roleDocument: `config/staff/${role.id}/ROLE.md`,
        roleRecord: `config/staff/${role.id}/role.json`,
      };
    }),
  };
}

function expectedOutputs(roles, archetypes) {
  const outputs = new Map();
  for (const role of roles) {
    const archetype = archetypes.get(role.archetype);
    const roleRoot = assertContained(join(STAFF_ROOT, role.id), STAFF_ROOT, `role ${role.id}`);
    outputs.set(join(roleRoot, "ROLE.md"), roleMarkdown(role, archetype));
    outputs.set(join(roleRoot, "role.json"), `${JSON.stringify(roleRecord(role, archetype), null, 2)}\n`);
  }
  outputs.set(ROLE_INDEX_PATH, `${JSON.stringify(compiledIndex(roles, archetypes), null, 2)}\n`);
  return new Map([...outputs.entries()].sort(([left], [right]) => compareText(left, right)));
}

function staleRolePacks(expectedRoleIds) {
  if (!existsSync(STAFF_ROOT)) return [];
  return readdirSync(STAFF_ROOT, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !expectedRoleIds.has(entry.name))
    .map((entry) => join(STAFF_ROOT, entry.name))
    .filter((path) => OUTPUT_NAMES.some((name) => existsSync(join(path, name))))
    .sort(compareText);
}

function driftFor(outputs, expectedRoleIds) {
  const drift = [];
  for (const [path, expected] of outputs) {
    if (!existsSync(path)) {
      drift.push({ kind: "missing", path: portablePath(path) });
    } else if (readFileSync(path, "utf8") !== expected) {
      drift.push({ kind: "content", path: portablePath(path) });
    }
  }
  for (const path of staleRolePacks(expectedRoleIds)) {
    drift.push({ kind: "stale-role-pack", path: portablePath(path) });
  }
  return drift.sort((left, right) => compareText(left.path, right.path) || compareText(left.kind, right.kind));
}

function isGeneratedRoleMarkdown(path) {
  return existsSync(path) && readFileSync(path, "utf8").startsWith(`${ROLE_MARKER}\n`);
}

function isGeneratedRoleJson(path) {
  if (!existsSync(path)) return false;
  try {
    return JSON.parse(readFileSync(path, "utf8"))?.generatedBy === GENERATOR_ID;
  } catch {
    return false;
  }
}

function assertStalePacksRemovable(paths) {
  for (const path of paths) {
    const markdownPath = join(path, "ROLE.md");
    const jsonPath = join(path, "role.json");
    invariant(!existsSync(markdownPath) || isGeneratedRoleMarkdown(markdownPath), `refusing to remove unmanaged ${portablePath(markdownPath)}`);
    invariant(!existsSync(jsonPath) || isGeneratedRoleJson(jsonPath), `refusing to remove unmanaged ${portablePath(jsonPath)}`);
  }
}

function atomicWrite(path, content) {
  assertNoSymlinkPath(path);
  mkdirSync(dirname(path), { recursive: true });
  assertNoSymlinkPath(path);
  const temporary = `${path}.tmp-${process.pid}`;
  writeFileSync(temporary, content, "utf8");
  if (existsSync(path)) unlinkSync(path);
  renameSync(temporary, path);
}

function writeOutputs(outputs, expectedRoleIds) {
  const stale = staleRolePacks(expectedRoleIds);
  assertStalePacksRemovable(stale);
  const written = [];
  const removed = [];
  for (const [path, content] of outputs) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
      atomicWrite(path, content);
      written.push(portablePath(path));
    }
  }
  for (const path of stale) {
    for (const name of OUTPUT_NAMES) {
      const outputPath = join(path, name);
      if (existsSync(outputPath)) {
        unlinkSync(outputPath);
        removed.push(portablePath(outputPath));
      }
    }
    try {
      rmdirSync(path);
    } catch {
      // Preserve unrelated files in a former generated role directory.
    }
  }
  return { written, removed };
}

function parseMode(argv) {
  const allowed = new Set(["--check", "--write"]);
  const unknown = argv.filter((arg) => !allowed.has(arg));
  invariant(unknown.length === 0, `unknown argument(s): ${unknown.join(", ")}`);
  const modes = argv.filter((arg) => allowed.has(arg));
  invariant(modes.length === 1, "use exactly one mode: --check or --write");
  return modes[0].slice(2);
}

export function generateStaffRolePacks({ mode }) {
  invariant(mode === "check" || mode === "write", "mode must be check or write");
  const archetypes = loadArchetypes();
  const roles = loadRoster(archetypes);
  const outputs = expectedOutputs(roles, archetypes);
  const expectedRoleIds = new Set(roles.map((role) => role.id));
  const before = driftFor(outputs, expectedRoleIds);

  if (mode === "check") {
    return {
      report: {
        schema: "orange5.hermes-staff-generation-report.v1",
        mode,
        status: before.length ? "DRIFT" : "IN_SYNC",
        roleCount: roles.length,
        archetypeCount: archetypes.size,
        executionProfileCount: archetypes.size,
        drift: before,
      },
      exitCode: before.length ? 1 : 0,
    };
  }

  const changes = writeOutputs(outputs, expectedRoleIds);
  const after = driftFor(outputs, expectedRoleIds);
  invariant(after.length === 0, `generated staff output still has drift: ${JSON.stringify(after)}`);
  return {
    report: {
      schema: "orange5.hermes-staff-generation-report.v1",
      mode,
      status: changes.written.length || changes.removed.length ? "WRITTEN" : "IN_SYNC",
      roleCount: roles.length,
      archetypeCount: archetypes.size,
      executionProfileCount: archetypes.size,
      written: changes.written,
      removed: changes.removed,
      drift: after,
    },
    exitCode: 0,
  };
}

if (import.meta.main) {
  try {
    const mode = parseMode(process.argv.slice(2));
    const { report, exitCode } = generateStaffRolePacks({ mode });
    process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
    process.exitCode = exitCode;
  } catch (error) {
    process.stderr.write(`${JSON.stringify({
      schema: "orange5.hermes-staff-generation-report.v1",
      status: "INVALID",
      error: error?.message || String(error),
    }, null, 2)}\n`);
    process.exitCode = 2;
  }
}
