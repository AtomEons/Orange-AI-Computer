function externalSource(label, ref) {
  return { kind: 'external-source', label, ref };
}

function mechanism({
  recordSchema,
  researchStatus,
  source,
  id,
  title,
  section,
  lineStart,
  lineEnd,
  attribution,
  invariant,
  owner,
  enforcementPoint,
  falsifier,
  failureThreshold,
  orangeGap,
  externalSources,
}) {
  return {
    schema: recordSchema,
    id,
    family: 'wave3-global-mechanism',
    title,
    provenance: {
      sourceDocument: source.document,
      sourceSha256: source.sha256,
      section,
      lineStart,
      lineEnd,
      attribution,
    },
    invariant,
    owner,
    enforcementPoint,
    falsifier,
    failureThreshold,
    rejectThreshold: failureThreshold,
    evidenceRefs: [
      {
        kind: 'registry-source',
        label: title,
        ref: source.document,
        lineStart,
        lineEnd,
      },
      ...externalSources,
    ],
    receiptRefs: [],
    status: researchStatus,
    sourceDecision: 'RESEARCH_ONLY',
    runtimeAuthority: 'none',
    orangeGap,
  };
}

